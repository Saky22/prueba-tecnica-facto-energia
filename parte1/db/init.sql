CREATE TABLE dbo.contratos (
    id               INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    cups             VARCHAR(22)   NOT NULL,
    titular          NVARCHAR(150) NOT NULL,
    nif              VARCHAR(15)   NOT NULL,
    tarifa           VARCHAR(10)   NOT NULL,
    estado           VARCHAR(10)   NOT NULL CHECK (estado IN ('activo', 'baja')),
    fecha_alta       DATE          NOT NULL,
    fecha_baja       DATE          NULL,
    digitos_contador TINYINT       NOT NULL
);

CREATE TABLE dbo.lecturas (
    id              INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    contrato_id     INT          NOT NULL REFERENCES dbo.contratos (id),
    fecha_lectura   DATE         NOT NULL,
    lectura_kwh     INT          NOT NULL, -- valor acumulado del contador
    tipo            VARCHAR(10)  NOT NULL CHECK (tipo IN ('real', 'estimada')),
    fecha_recepcion DATETIME2(0) NOT NULL
);

CREATE INDEX ix_contratos_cups ON dbo.contratos (cups);
CREATE INDEX ix_lecturas_contrato_fecha ON dbo.lecturas (contrato_id, fecha_lectura);
